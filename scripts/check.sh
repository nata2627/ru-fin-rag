#!/usr/bin/env bash
# Проверка перед тем, как считать задачу сделанной. Падает на первой ошибке,
# чтобы нельзя было отчитаться о готовности при красном тесте.
set -euo pipefail

cd "$(dirname "$0")/.."
PY=${PY:-.venv/bin/python}

# Проверка запуском, а не по признаку файла: в CI PY это имя команды из PATH,
# а не путь к venv, и `-x python` там ложно срабатывает как отсутствие окружения.
if ! "$PY" -c "import rufinrag" >/dev/null 2>&1; then
  echo "Нет окружения $PY с установленным пакетом. Собрать: make venv" >&2
  exit 1
fi

echo "== ruff"
# Каталог scripts линтер не видел до 28.10.2026, хотя именно эти скрипты
# создают каждое публичное число. Формат пока проверяется только там, где он
# уже приведен: ruff format по всем 49 скриптам идет отдельной правкой.
"$PY" -m ruff check src tests dags scripts
"$PY" -m ruff format --check src tests dags

# Отдельным шагом, потому что это выход задач 7.1 и 7.2: сервис обязан
# отвечать в обоих режимах, а запросу без опоры отказывать. Общий прогон ниже
# идет без этих тестов, чтобы они не считались дважды.
echo "== ответ: выдержки, генерация подставной моделью, отказ без опоры"
"$PY" -m pytest -m answer --ignore=tests/test_router.py

# Тоже отдельным шагом: выход задачи 8.2 это маршрут на каждый инструмент,
# включая отказ, и в выводе проверки это должно быть видно строкой. Без группы
# зависимостей router тесты сами себя пропускают.
echo "== роутер: маршруты поиска, графа, уточнения и отказа"
"$PY" -m pytest tests/test_router.py

echo "== pytest"
"$PY" -m pytest -m "not answer" --ignore=tests/test_router.py

echo "== числа публичных текстов"
"$PY" scripts/verify_numbers.py

echo "== секреты в рабочем дереве"
scripts/check_secrets.sh

echo "check: зеленый"
