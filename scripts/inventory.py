#!/usr/bin/env python3
"""Размеры того, что открыто и что закрыто, числом из файла.

README называет вес открытых и закрытых каталогов части А, и до 28.10.2026 эти
числа стояли в тексте руками: «26 МБ» выдач прогонов на деле оказались 62,7 МиБ,
то есть читатель видел число в два с половиной раза меньше настоящего. Счет
нельзя держать в голове, он растет с каждым прогоном, поэтому его считает этот
скрипт, а `verify_numbers.py` сверяет напечатанное с посчитанным.

Единица одна, МиБ и КиБ по основанию 1024: `du` печатает блоки диска (у 63
файлов выводов это 544 КБ против 386 КиБ настоящих байтов), и смешивать блоки с
байтами в публичном тексте нельзя.

Запуск: python scripts/inventory.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "inventory.json"

# Каталоги и файлы, вес которых назван в README. Ключ это имя в тексте.
ЦЕЛИ = {
    "выводы прогонов части А": "retrieval/data/results",
    "выдачи прогонов части А": "retrieval/data/runs",
    "веса моделей части А": "retrieval/data/weights",
    "корпус набора на HuggingFace": "retrieval/data/benchmark/corpus.jsonl",
    "корпус сервиса в репозитории": "data/corpus/chunks.jsonl.gz",
}


def посчитать(путь: Path) -> dict | None:
    """Отдельно то, что открыто читателю, и отдельно то, что лежит на диске.

    Числа README говорят про открытое, а не про рабочее дерево: у части А в
    каталоге выводов может лежать свежий файл, который еще не в git, и подпись
    «63 файла открыты» обязана считать именно отслеживаемые."""
    if not путь.exists():
        return None
    если_файл = [путь] if путь.is_file() else [ф for ф in путь.rglob("*") if ф.is_file()]
    отслеживаемые = [ROOT / имя for имя in git_files(путь)]
    return {
        "файлов на диске": len(если_файл),
        "байт на диске": sum(ф.stat().st_size for ф in если_файл),
        "файлов в git": len(отслеживаемые),
        "байт в git": sum(ф.stat().st_size for ф in отслеживаемые if ф.exists()),
    }


def git_files(путь: Path) -> list[str]:
    import subprocess

    отн = путь.relative_to(ROOT).as_posix()
    вывод = subprocess.run(["git", "ls-files", отн], cwd=ROOT, capture_output=True, text=True)
    return [с for с in вывод.stdout.split("\n") if с]


def главное() -> dict:
    записи = {}
    for имя, отн in ЦЕЛИ.items():
        мера = посчитать(ROOT / отн)
        if мера is None:
            записи[имя] = {"путь": отн, "на диске": False}
            continue
        записи[имя] = {
            "путь": отн,
            "на диске": True,
            "открыт": мера["файлов в git"] > 0,
            **мера,
            "КиБ в git": round(мера["байт в git"] / 1024, 1),
            "МиБ в git": round(мера["байт в git"] / 1024 / 1024, 1),
            "КиБ на диске": round(мера["байт на диске"] / 1024, 1),
            "МиБ на диске": round(мера["байт на диске"] / 1024 / 1024, 1),
        }
    return {"единица": "байт, КиБ и МиБ по основанию 1024", "записи": записи}


def main() -> None:
    данные = главное()
    OUT.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for имя, з in данные["записи"].items():
        if not з["на диске"]:
            print(f"{имя}: нет на диске ({з['путь']})")
            continue
        if з["открыт"]:
            print(
                f"{имя}: открыто {з['файлов в git']} файлов, {з['КиБ в git']} КиБ "
                f"({з['МиБ в git']} МиБ); на диске {з['файлов на диске']}"
            )
        else:
            print(
                f"{имя}: вне git, на диске {з['файлов на диске']} файлов, "
                f"{з['МиБ на диске']} МиБ"
            )


if __name__ == "__main__":
    main()
