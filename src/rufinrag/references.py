"""Номера нормативных актов в тексте.

Порт выражения из части А (`ru-fin-retrieval`, `src/rufin/references.py`), где
оно читает номер акта из текста вопроса для фильтра по метаданным. Здесь тот же
номер читается из текста самого акта, чтобы узнать, на какие акты он ссылается.

Почему порт, а не импорт пакета части А. Пакет `rufin` ставится только
дополнением `collect` (`pyproject.toml`) и нужен ночной докачке, а образ сервиса
его не содержит: он тянет `transformers` и `sentencepiece`. Граф ссылок нужен
сервису в онлайне, поэтому выражение живет здесь, а совпадение с частью А
держится тестом `tests/test_graph.py`: при наличии части А на диске оба разбора
прогоняются на одних строках и обязаны дать один ответ.

Берутся только номера с буквенным суффиксом («590-П», «115-ФЗ», «5348-У»):
именно они совпадают с полем `number` фрагмента. Голый «№ 1» номером акта не
является, и в части А он не брался по той же причине.
"""

from __future__ import annotations

import re

# Номер акта с буквенным суффиксом: «590-П», «115-ФЗ», «ИН-08-23/42».
# Выражение дословно совпадает с `LETTERED` части А, менять его нельзя: на нем
# посчитан фильтр по номеру акта (EXPERIMENTS, S8), и расхождение сделало бы
# числа графа и фильтра несравнимыми.
LETTERED = r"(?:\d+[-–][А-ЯA-Z]{1,3}|[А-Я]{2}-\d+-\d+/\d+)"
ACT_NUMBER = re.compile(LETTERED, re.I)


def act_numbers(text: str) -> list[str]:
    """Номера актов, названные в тексте, в порядке первого появления."""
    found: list[str] = []
    for raw in ACT_NUMBER.findall(text):
        number = normalize(raw)
        if number not in found:
            found.append(number)
    return found


def count_act_numbers(text: str) -> dict[str, int]:
    """То же, но с числом упоминаний каждого номера.

    Нужно графу: «акт упомянут один раз в преамбуле» и «акт упомянут сорок раз
    по всему тексту» это разная сила связи, и доля ссылок за пределы корпуса
    считается по упоминаниям, а не по разным номерам.
    """
    counts: dict[str, int] = {}
    for raw in ACT_NUMBER.findall(text):
        number = normalize(raw)
        counts[number] = counts.get(number, 0) + 1
    return counts


def normalize(raw: str) -> str:
    """Верхний регистр и обычный дефис: в текстах встречается «590-п» и тире."""
    return raw.upper().replace("–", "-").replace("—", "-")
