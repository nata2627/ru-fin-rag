"""Отбор лучших k при равных оценках: одинаково на любой машине.

Зачем отдельная функция. BM25 дает одинаковые оценки чаще, чем кажется: у
запроса про ключевую ставку три фрагмента получили ровно 39,001183, и все три
претендовали на десятое место. Кто из них попадет в выдачу, решал
`np.argpartition`, а он выбирает среди равных произвольно и по-разному на
разных сборках numpy. На маке выдача совпадала с частью А, в Linux CI тот же
запрос разошелся: прогон `check` от 22.10.2026 упал на `dv00008`.

Поэтому ничьи разрешаются явно, по возрастанию номера фрагмента в корпусе.
Порядок корпуса идет от даты акта, то есть при равной оценке первым стоит акт
постарше. Это произвольное правило, но оно записано и воспроизводится.
"""

from __future__ import annotations

import numpy as np


def top_k(scores: np.ndarray, k: int) -> np.ndarray:
    """Индексы k лучших оценок, по убыванию оценки и по возрастанию индекса."""
    if k <= 0:
        # Отрицательный k в numpy отдает правдоподобный, но чужой ответ:
        # `[:k]` отрезает с конца, и вместо ошибки получается тихо неверная
        # выдача. Такое приходит из конфигурации (`candidates`), поэтому
        # отвечаем словами, а не срезом.
        raise ValueError(f"нужно k больше нуля, пришло {k}")
    if k >= scores.shape[0]:
        return np.argsort(-scores, kind="stable")[:k]
    # NaN ломает и порядок, и порог окна: сравнение с ним всегда ложно, и
    # окно могло оказаться пустым, то есть поиск молча возвращал бы ноль
    # результатов. Оценка, которой нет, это худший результат, а не лучший.
    if np.isnan(scores).any():
        scores = np.nan_to_num(scores, nan=-np.inf)
    # Окно берется с запасом: в него входят все, кто не хуже k-й оценки, иначе
    # ничья на границе решалась бы тем же произволом, что и раньше.
    part = np.argpartition(-scores, k)[:k]
    window = np.flatnonzero(scores >= scores[part].min())
    return window[np.argsort(-scores[window], kind="stable")[:k]]
