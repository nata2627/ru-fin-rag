"""Токенизация для BM25.

Перенесено из части А (`ru-fin-retrieval`, `src/rufin/retrieval/text.py`) без
изменений формулы: индекс сервиса должен давать ту же выдачу, что бенчмарк, и
это проверяется тестом на совпадение выдач. Отсюда же точный пин версии
стеммера в `pyproject.toml`: правила Snowball между версиями меняются, и
разные версии по обе стороны развели бы две выдачи.

Что здесь есть и чего нет. Форма русского слова снимается стеммером Snowball
(решение 16 от 23.10.2026): «принципы» в запросе и «принципами» в тексте это
одно слово, и без этого лексическая ступень теряла около 0,08 NDCG@10
(документ 14 части А). Чистки запроса из части А (`normalize_query`: снятие
канцелярита и раскрытие сокращений) здесь нет: она проверялась абляцией и в
рекомендованную связку не вошла.

Буква «е с точками» приводится к «е» на обеих сторонах, и в запросе, и в
документе. В корпусе она встречается в 10 фрагментах из 62 594, а в живых
вопросах практиков в 2 процентах текстов, так что без приведения запрос с ней
не находит ничего, хотя слово в корпусе есть.
"""

from __future__ import annotations

import re
from functools import lru_cache

import snowballstemmer

_STEMMER = snowballstemmer.stemmer("russian")

# Стеммить имеет смысл только русское слово: номер акта («590-п»), латиница и
# числа идут в индекс как есть.
_RUSSIAN_WORD = re.compile(r"^[а-я]+$")

# Номер акта отдельной ветвью: в живых вопросах это адрес ответа, и он обязан
# остаться одним токеном. Формы выведены из данных, а не из головы: в поле
# `number` у актов корпуса их две, «3054-У» (1552 акта) и «1/801-П» (2); среди
# 24 номеров, названных в эталонных вопросах, те же плюс информационные письма
# «ИН-03-23/109» (5 из 24).
#
# Границу слова после буквенного суффикса читать как главное условие: без нее
# то же `{1,3}` режет любое русское слово с дефисом («кредитно-денежный» ->
# «кредитно-ден» и «ежный»), а таких слов в корпусе 30 800 вхождений.
_ACT_NUMBER = r"\d+(?:/\d+)?-[а-яa-z]{1,3}(?![а-яa-z])|[а-яa-z]{2,4}-\d+(?:[-/]\d+)+"
# токен: номер акта целиком, иначе слово или число. Отдельной оговорки про
# дефис у слова здесь нет нарочно: дефисное слово распадается на два полных.
_TOKEN = re.compile(rf"(?:{_ACT_NUMBER})|[а-яёa-z0-9]+", re.I)

STOPWORDS = frozenset(
    """
    и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по
    только ее мне было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если
    уже или ни быть был него до вас нибудь опять уж вам сказал ведь там потом себя
    ничего ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без
    будто чего раз тоже себе под будет ж тогда кто этот того потому этого какой совсем
    ним здесь этом один почти мой тем чтобы нее были куда зачем всех никогда можно при
    наконец два об другой хоть после над больше тот через эти нас про всего них какая
    много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя
    такой им более всегда конечно всю между
    """.split()
)


def split_tokens(text: str) -> list[str]:
    """Разбить текст на токены, формы слов не трогая.

    Номера актов остаются целыми: по ним часто и ищут, а разбиение «590-П» на
    «590» и «п» такой запрос убивает. Целыми остаются все четыре формы,
    встреченные в корпусе и в вопросах: «590-П», «86-ФЗ», «1/801-П» и письма
    «ИН-03-23/109». До 23.10.2026 последняя рассыпалась на «ин», «03», «23»,
    «109», то есть вопрос про одно письмо шел в индекс с приставкой, общей у
    всех писем, и тремя частыми числами.
    """
    out = []
    for raw in _TOKEN.findall(text):
        token = raw.lower().replace("ё", "е")
        if token not in STOPWORDS:
            out.append(token)
    return out


@lru_cache(maxsize=131072)
def stem(token: str) -> str:
    """Основа русского слова по Snowball; остальное возвращается как есть.

    Номер акта стеммер не трогает и сам («590-п» так и остается «590-п»), но
    условие стоит явно: номер это адрес ответа, и зависеть здесь от
    внутренностей чужой библиотеки незачем.

    Кэш ограничен нарочно. Различных токенов во всем корпусе 85 397, то есть
    в кэш он укладывается целиком, а сервис на хостинге живет месяцами и
    видит поток непохожих запросов: неограниченный кэш там растет без
    предела. Документы сервис при этом не токенизирует вовсе, индекс
    приходит собранным.

    Снятая форма не всегда верна. Snowball для русского разводит формы одного
    слова там, где основа кончается на «ив» или «ал»: «норматив» дает
    «нормат», а «нормативы» и «норматива» дают «норматив». Это известный
    дефект правил, он измерен вместе с прибавкой и не спрятан.
    """
    if not _RUSSIAN_WORD.match(token):
        return token
    return _STEMMER.stemWord(token)


def tokenize(text: str) -> list[str]:
    """Рабочая токенизация BM25: разбиение плюс снятие формы слова."""
    return [stem(t) for t in split_tokens(text)]
