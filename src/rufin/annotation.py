"""Разметка пула: единая инструкция, сборка оценки, согласие разметчиков.

Пул размечает языковая модель-судья: руками 142 вопроса по двести восемьдесят
кандидатов не размечает никто. Это принятая практика, но у нее есть цена, и
цену надо назвать числом. Судья это прибор, у прибора есть погрешность, и
мерится она тремя числами, а не одним (`scripts/kappa.py`): согласие с
человеком, согласие двух прогонов одной модели между собой и записанный стек
вывода. Первое без второго ничего не значит: 23.10.2026 та же модель на тех же
150 парах дала каппу 0,307 вместо 0,408 только из-за смены сборки движка.

Чтобы каппа мерила согласие, а не разницу в инструкциях, инструкция одна.
Поэтому она лежит здесь текстом, отсюда попадает в подсказку судье и в шапку
листа для человека, а `docs/ANNOTATION_GUIDE.md` обязан совпадать с ней
дословно: это проверяется тестом.

Оценка 0/1/2 не ставится напрямую. Разметчик отвечает на два отдельных
вопроса «да» или «нет», и оценка собирается из ответов функцией `scale_of`
по правилу, напечатанному в самой инструкции. Причина в разборе двадцати
провалов (`docs/16-razbor-provalov.md`): на тройной шкале разметчики спорили
не о существе, а о том, куда отнести фрагмент, который отвечает только
вместе с соседним, и фрагмент общей нормы, по которой надо рассуждать.
Два вопроса эти случаи разводят, а шкала остается той же, поэтому прежние
числа сравнимы через сборку.

Выборка для человека берется стратифицированной по оценкам судьи. Случайная
выборка из пула состояла бы почти из одних нулей: на двести восемьдесят
кандидатов релевантны единицы, и каппа на такой выборке померила бы согласие
в том, что случайный фрагмент нерелевантен.
"""
from __future__ import annotations

import random
import re
from collections import Counter
from typing import Sequence

RUBRIC = """\
Оценивается пара «запрос, фрагмент нормативного акта». Оценка не ставится.
Нужны два ответа, каждый «да» или «нет», и в одном случае еще пометка типа.
Оценка 0, 1 или 2 собирается из ответов правилом, напечатанным в конце.

ВОПРОС 1. Есть ли в этом фрагменте ответ целиком?

«да», если по одному этому фрагменту можно ответить по существу: не открывая
другого фрагмента, другого пункта и другого акта, ничего не додумывая. Это и
есть самодостаточность, и больше ничего вопрос 1 не спрашивает.
«нет» во всех остальных случаях, в том числе когда ответ в тексте есть
наполовину.

ВОПРОС 2. Помогает ли этот фрагмент ответить вместе с другими фрагментами?

Задается только тогда, когда на вопрос 1 ответ «нет».
«да», если фрагмент нужен для ответа: без него ответ не собрать, либо он
называет ту самую норму, пункт, термин, счет или механизм, о котором
спрашивают.
«нет», если фрагмент к делу не относится: другая тема, другой вид операций,
совпали только слова.

ПОМЕТКА ТИПА. Ставится только тогда, когда на вопрос 1 ответ «нет», а на
вопрос 2 «да». Одна из трех:

«общая норма» — фрагмент называет правило, по которому надо рассуждать, а
    прямого ответа на заданный вопрос в его тексте нет вовсе. Так выглядит
    общий пункт о том, как оценивается финансовое положение заемщика, когда
    спрашивают про отдельный вид дохода: пункт отправляет оценивать по своим
    правилам, а слов вопроса (проценты по вкладу, купон, дивиденды) в нем
    не встречается.

«часть ответа» — в тексте есть часть ответа, а остальное в другом пункте или
    в другом акте, и вместе они отвечают. Сюда же идет вопрос о совместном
    применении двух норм.

«иное» — фрагмент продвигает к ответу, но ни общей нормой, ни частью ответа
    не является: определение употребленного термина, отсылка к нужному
    правилу, такое же правило для другого вида организаций.

Правила, без которых ответы разойдутся.

1. Оценивается фрагмент, а не акт. Нужный акт с ненужным пунктом это «нет»
   на вопрос 1.
2. Подпункт отвечает за себя. Если вопрос называет пункт, а во фрагменте
   стоит его подпункт, и этот подпункт на вопрос отвечает, на вопрос 1 ответ
   «да». То, что заголовок раздела называет пункт выше, значения не имеет.
3. Оценивается смысл, а не слова. Совпадение слов вопроса и фрагмента не
   повод для «да», несовпадение не повод для «нет»: вопрос задан живым
   языком, а акт написан канцелярским.
4. «да» на вопрос 1 ставится только тогда, когда фрагмент отвечает ТОМУ, КТО
   СПРАШИВАЕТ. Правило для некредитной финансовой организации не отвечает
   на вопрос кредитной организации, даже если формулировка совпадает слово
   в слово: это «нет» на вопрос 1, «да» на вопрос 2 и тип «иное». То же про
   другой вид лица: правило для юридических лиц не отвечает на вопрос про
   индивидуальных предпринимателей.
5. Если в запросе несколько вопросов, «да» на вопрос 1 ставится, когда
   фрагмент полностью отвечает на главный из них. Ответ на попутный вопрос
   при молчании о главном это «нет» на вопрос 1, «да» на вопрос 2 и тип
   «часть ответа».
6. Фрагменты нарезаны механически, и обрыв на полуслове сам по себе ответы
   не меняет. Но оценивается то, что в фрагменте ЕСТЬ: если текст обрывается
   там, где должен был начаться ответ, ответа в нем нет, и на вопрос 1 это
   «нет».
7. Широкое совпадение темы это «нет» на вопрос 2. «Тоже про резервы», «тоже
   про отчетность», «тоже про залог» не делают фрагмент нужным для ответа.
8. Если запрос непонятен без контекста, который в нем не назван, оба ответа
   «нет»: найти на него ответ нельзя, и поиску это не в упрек.
9. Сомнение разрешается в пользу «нет», отдельно на каждом вопросе. Незнание
   предмета не повод ответить «да» на всякий случай.

ПРАВИЛО СБОРКИ ОЦЕНКИ. Напечатано затем, чтобы прежние числа остались
сравнимыми: шкала та же, меняется только способ ее получить.

   вопрос 1 «да»                      оценка 2
   вопрос 1 «нет», вопрос 2 «да»      оценка 1
   вопрос 1 «нет», вопрос 2 «нет»     оценка 0

Пометка типа в оценку не входит. Она нужна затем, чтобы «общую норму» и
«часть ответа» можно было посчитать отдельно: это две разные причины, по
которым фрагмент оказывается единицей, и лечатся они по-разному.
"""

# Формат ответа судьи. В листе человека те же ответы стоят колонками, поэтому
# в инструкции формата нет: инструкция про содержание ответов, а не про то,
# куда их записать.
ANSWER_FORMAT = """\
Ответ тремя строками и ничем больше:
1: да или нет
2: да или нет (если в строке 1 стоит «да», напиши «-»)
тип: общая, часть, иное (если в строке 1 стоит «да» или в строке 2 «нет», \
напиши «-»)"""

TYPES = ("общая", "часть", "иное")

_YES_NO = re.compile(r"^\s*(?:вопрос\s*)?([12])\s*[:.)]\s*(да|нет|-)", re.I | re.M)
# Пометка типа ищется в любом месте ответа, а не только с начала строки:
# без нумерации модель пишет ее в той же строке, что и ответы.
_TYPE = re.compile(r"\bтип\s*[:.)]\s*(общая|часть|иное|-)", re.I)
# Ответ без нумерации: «нет да тип: часть ответа». Так отвечает
# `Qwen2.5-32B-Instruct-AWQ`, и на этом 24.10.2026 не разобралось 150 ответов
# из 150, то есть весь прогон. Нумерация это оформление, а не ответ, и терять
# из-за нее разметку нельзя. Порядок при этом остается значащим: первое
# «да/нет» отвечает на первый вопрос, второе на второй.
_BARE = re.compile(r"(?<![а-яё])(да|нет|-)(?![а-яё])", re.I)


def parse_answers(raw: str) -> tuple[bool, bool, str] | None:
    """Разобрать ответ разметчика. None, если ответа нет.

    Выдумывать ответ из обрывка нельзя: пара без разбора идет в отдельный
    счетчик, а не в оценку по умолчанию. Второй ответ при первом «да» не
    спрашивается и читается как «нет»: на оценку он все равно не влияет.
    """
    answers = {m.group(1): m.group(2).lower() for m in _YES_NO.finditer(raw)}
    first, second = answers.get("1"), answers.get("2")
    if first is None or second is None:
        # Нумерованный разбор держится за начало строки, а ответ бывает одной
        # строкой: «1: нет 2: да тип: часть ответа». Тогда номер находится
        # только у первого ответа, и второй добирается по порядку.
        по_порядку = _by_order(raw)
        first = first if first is not None else по_порядку[0]
        second = second if second is not None else по_порядку[1]
    if first not in ("да", "нет"):
        return None
    whole = first == "да"
    if not whole and second not in ("да", "нет"):
        return None
    together = second == "да"
    m = _TYPE.search(raw)
    kind = m.group(1).lower() if m else "-"
    if kind not in TYPES or whole or not together:
        kind = "-"
    return whole, together, kind


def _by_order(raw: str) -> tuple[str | None, str | None]:
    """Ответы по порядку, когда модель не поставила номера.

    Строка типа читается отдельно, иначе «тип: иное» и «общая норма» подмешали
    бы свои слова в счет ответов. Берутся первые два «да», «нет» или «-» из
    того, что осталось.
    """
    head = re.split(r"\bтип\b", raw, maxsplit=1, flags=re.I)[0]
    found = [m.group(1).lower() for m in _BARE.finditer(head)]
    if len(found) < 2:
        return None, None
    return found[0], found[1]


def scale_of(whole: bool, together: bool) -> int:
    """Правило сборки оценки из двух ответов, то самое, что в инструкции."""
    if whole:
        return 2
    return 1 if together else 0


def cohen_kappa(a: Sequence[int], b: Sequence[int], weighted: bool = False) -> float:
    """Каппа Коэна: согласие сверх того, что дало бы совпадение случайно.

    Взвешенный вариант (квадратичные веса) нужен потому, что оценки
    упорядочены: расхождение «2 против 0» хуже, чем «2 против 1», а простая
    каппа считает их одинаковыми промахами.
    """
    if len(a) != len(b):
        raise ValueError("списки оценок разной длины")
    if not a:
        raise ValueError("пустая выборка")
    labels = sorted(set(a) | set(b))
    n = len(a)
    ca, cb = Counter(a), Counter(b)

    def w(x: int, y: int) -> float:
        if not weighted:
            return 0.0 if x == y else 1.0
        span = (labels[-1] - labels[0]) or 1
        return ((x - y) / span) ** 2

    observed = sum(w(x, y) for x, y in zip(a, b)) / n
    expected = sum(w(x, y) * ca[x] * cb[y] for x in labels for y in labels) / (n * n)
    if expected == 0:
        return 1.0 if observed == 0 else 0.0
    return 1 - observed / expected


def kappa_interval(a: Sequence[int], b: Sequence[int], weighted: bool = False,
                   size: int = 0, reps: int = 4000,
                   seed: int = 20261024) -> tuple[float, float]:
    """Интервал каппы бутстрэпом по парам.

    `size` меньше длины выборки отвечает на вопрос «насколько шире стал бы
    интервал, размечай человек не 150 пар, а меньше»: это не оценка каппы
    на подвыборке, а оценка цены сокращения.
    """
    if len(a) != len(b):
        raise ValueError("списки оценок разной длины")
    n = size or len(a)
    rnd = random.Random(seed)
    values: list[float] = []
    for _ in range(reps):
        idx = [rnd.randrange(len(a)) for _ in range(n)]
        try:
            values.append(cohen_kappa([a[i] for i in idx], [b[i] for i in idx],
                                      weighted=weighted))
        except ValueError:
            continue
    if not values:
        raise ValueError("бутстрэп не дал ни одного значения")
    values.sort()
    return values[int(0.025 * len(values))], values[int(0.975 * len(values))]


def kappa_verdict(k: float) -> str:
    """Словесная шкала Лэндиса и Коха, чтобы число не читали как проценты."""
    if k < 0.0:
        return "хуже случайного"
    if k < 0.20:
        return "ничтожное согласие"
    if k < 0.40:
        return "слабое согласие"
    if k < 0.60:
        return "умеренное согласие"
    if k < 0.80:
        return "существенное согласие"
    return "почти полное согласие"


def stratified_sample(items: Sequence[dict], key: str, size: int,
                      seed: int = 13) -> list[dict]:
    """Выборка, в которую попадают все оценки судьи, а не только нули.

    Доли берутся равными, а не пропорциональными: в пуле двоек единицы
    процента, и пропорциональная выборка в 150 пар дала бы две-три двойки,
    то есть ничего не сказала бы именно про те оценки, ради которых
    разметка и делается.
    """
    groups: dict[str, list[dict]] = {}
    for item in items:
        groups.setdefault(str(item[key]), []).append(item)
    rnd = random.Random(seed)
    out: list[dict] = []
    order = sorted(groups)
    share = max(1, size // max(1, len(order)))
    for name in order:
        pool = sorted(groups[name], key=lambda r: (r.get("query_id", ""),
                                                   r.get("chunk_id", "")))
        rnd.shuffle(pool)
        out += pool[:share]
    # если в какой-то оценке пар не хватило, добираем из самых многочисленных
    if len(out) < size:
        taken = {(r.get("query_id"), r.get("chunk_id")) for r in out}
        rest = [r for r in items if (r.get("query_id"), r.get("chunk_id")) not in taken]
        rnd.shuffle(rest)
        out += rest[:size - len(out)]
    return out[:size]
