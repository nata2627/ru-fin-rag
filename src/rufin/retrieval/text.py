"""Подготовка текста для BM25 и нормализация запросов.

Форма русского слова снимается стеммером Snowball (решение 16 от 23.10.2026).
До этого ее не снимал никто, и контроль на чужих данных показал цену: наш BM25
отставал от чужого на его же наборе на 0,068 NDCG@10, а на нашем корпусе
нормализация стоит около 0,08 (`docs/14-kontrol-na-chuzhih-dannyh.md`).

Нормализация запроса вынесена отдельно и проверяется абляцией: снятие
канцелярита («каков порядок…» → «порядок») и раскрытие сокращений («КО» →
«кредитная организация») могут и помочь, и навредить, и это надо измерить,
а не решить заранее.
"""
from __future__ import annotations

import re
from functools import lru_cache

import snowballstemmer

_STEMMER = snowballstemmer.stemmer("russian")

# Стеммить имеет смысл только русское слово: номер акта («590-п»), латиница
# и числа идут в индекс как есть.
_РУССКОЕ_СЛОВО = re.compile(r"^[а-я]+$")

# токен: слово, число или номер акта вида 590-П, 86-ФЗ
_TOKEN = re.compile(r"[а-яёa-z0-9]+(?:-[а-яёa-z]{1,3})?", re.I)

# служебные слова, не несущие смысла в запросе к нормативке
STOPWORDS = {
    "и", "в", "во", "не", "что", "он", "на", "я", "с", "со", "как", "а", "то", "все",
    "она", "так", "его", "но", "да", "ты", "к", "у", "же", "вы", "за", "бы", "по",
    "только", "ее", "мне", "было", "вот", "от", "меня", "еще", "нет", "о", "из",
    "ему", "теперь", "когда", "даже", "ну", "вдруг", "ли", "если", "уже", "или",
    "ни", "быть", "был", "него", "до", "вас", "нибудь", "опять", "уж", "вам",
    "сказал", "ведь", "там", "потом", "себя", "ничего", "ей", "может", "они",
    "тут", "где", "есть", "надо", "ней", "для", "мы", "тебя", "их", "чем", "была",
    "сам", "чтоб", "без", "будто", "чего", "раз", "тоже", "себе", "под", "будет",
    "ж", "тогда", "кто", "этот", "того", "потому", "этого", "какой", "совсем",
    "ним", "здесь", "этом", "один", "почти", "мой", "тем", "чтобы", "нее",
    "были", "куда", "зачем", "всех", "никогда", "можно", "при", "наконец", "два",
    "об", "другой", "хоть", "после", "над", "больше", "тот", "через", "эти",
    "нас", "про", "всего", "них", "какая", "много", "разве", "три", "эту", "моя",
    "впрочем", "хорошо", "свою", "этой", "перед", "иногда", "лучше", "чуть",
    "том", "нельзя", "такой", "им", "более", "всегда", "конечно", "всю", "между",
}

# канцелярские обороты в начале вопроса — смысла не несут, но забивают BM25
_BOILERPLATE = re.compile(
    r"^\s*(?:каков[аоы]?|какой|какие|какая|что\s+(?:такое|является)|"
    r"в\s+каком\s+порядке|каким\s+образом|как\s+(?:именно\s+)?|"
    r"подскажите,?\s*|скажите,?\s*|please\s+|)\s*", re.I)

# сокращения, принятые в банковском надзоре
ABBREVIATIONS = {
    "ко": "кредитная организация",
    "нфо": "некредитная финансовая организация",
    "цб": "банк россии",
    "пвр": "подход на основе внутренних рейтингов",
    "нпф": "негосударственный пенсионный фонд",
    "пос": "портфель однородных ссуд",
    "офр": "организация финансового рынка",
    "уэс": "уполномоченное экономическое соглашение",
    "мсфо": "международные стандарты финансовой отчетности",
    "рсбу": "российские стандарты бухгалтерского учета",
    "од": "операционный день",
    "вса": "внутренняя система аудита",
}


def split_tokens(text: str) -> list[str]:
    """Разбить текст на токены, формы слов не трогая.

    Номера актов («590-П») сохраняются целиком: по ним часто и ищут,
    а разбиение на «590» и «п» такой запрос убивает.

    Буква «ё» приводится к «е». Это не косметика, а условие сопоставимости:
    в корпусе «ё» встречается в 10 фрагментах из 62 594, а в живых вопросах
    практиков — в 2% текстов. Без приведения «отчётность» и «отчетность»
    становятся разными токенами, и запрос с «ё» не находит ничего,
    хотя нужное слово в корпусе есть. Приводим обе стороны, и запрос,
    и документ, иначе несовпадение останется.

    Отдельной функцией это нужно затем, что на ней считается абляция
    морфологии (`scripts/morphology_effect.py`): прежнее состояние поиска
    должно оставаться измеримым тем же кодом, которым меряются замены.
    """
    out = []
    for raw in _TOKEN.findall(text):
        token = raw.lower().replace("ё", "е")
        if token not in STOPWORDS:
            out.append(token)
    return out


@lru_cache(maxsize=131072)
def stem(token: str) -> str:
    """Основа русского слова по Snowball; остальное возвращается как есть.

    Номер акта стеммер не трогает и сам («590-п» так и остается «590-п»), но
    условие стоит явно: на номерах держится фильтр из документа 12, и
    зависеть здесь от внутренностей чужой библиотеки незачем.

    Кэш ограничен нарочно. Различных токенов во всем корпусе 85 397, то есть
    в кэш он укладывается целиком, а сервис живет месяцами и видит поток
    непохожих запросов: неограниченный кэш там растет без предела.

    Снятая форма не всегда верна. Snowball для русского разводит формы
    одного слова там, где основа кончается на «ив» или «ал»: «норматив»
    дает «нормат», а «нормативы» и «норматива» дают «норматив». Это
    известный дефект правил, и он учтен в цене замера, а не спрятан.
    """
    if not _РУССКОЕ_СЛОВО.match(token):
        return token
    return _STEMMER.stemWord(token)


def tokenize(text: str) -> list[str]:
    """Рабочая токенизация BM25: разбиение плюс снятие формы слова."""
    return [stem(t) for t in split_tokens(text)]


def truncate_tokens(text: str, n: int = 6) -> list[str]:
    """Грубая замена морфологии: токен обрезается до n первых символов.

    Это диагностика, которой измерена цена вопроса, а в рабочий поиск пошел
    стеммер (решение 16). Обрезка склеивает большинство падежных форм без
    словаря и без зависимостей, но склеивает заодно разные слова («решение»
    и «решетка») и 5 номеров актов из 24. Функция остается затем, что замер
    стеммера против нее считается на одних данных.
    """
    return [t[:n] for t in split_tokens(text)]


def normalize_query(q: str) -> str:
    """Снять канцелярит и раскрыть сокращения. Проверяется абляцией.

    Исходный запрос сохраняется отдельно: если чистка съела его целиком
    («Каков» — это весь запрос и он же весь зачин), возвращается исходный.
    Пустой запрос не находит ничего, и такой провал по метрикам выглядел бы
    как провал поиска.
    """
    исходный = q.strip()
    очищенный = _BOILERPLATE.sub("", исходный)
    out = []
    for w in re.split(r"(\W+)", очищенный):
        low = w.lower()
        out.append(ABBREVIATIONS[low] if low in ABBREVIATIONS else w)
    return "".join(out).strip() or исходный
