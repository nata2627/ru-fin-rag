-- У отвеченного запроса обязана быть ступень `total` в карте задержек.
--
-- Ломалось бы молча: модель задержки разворачивает карту ступеней, и запрос с
-- пустой картой просто не дает строк. Такой запрос исчез бы из задержки,
-- остался бы в трафике, и квантиль считался бы по подмножеству, о котором
-- никто не знает. Ступень `total` сервис складывает сам (search.py), то есть
-- ее отсутствие у `ok` означает, что событие записано не тем путем.

select
    request_id,
    received_at,
    outcome,
    hits,
    length(mapKeys(timings_ms)) as stages
from {{ ref('stg_queries') }}
where outcome = 'ok'
    and (not has(mapKeys(timings_ms), 'total') or total_ms <= 0)
