"""Ячейки тетрадей из `notebooks/` обязаны компилироваться.

Повод прямой. Тетрадь этапа 3б уехала на Kaggle с незакрытой строкой
в последней ячейке: тройные кавычки генератора съели кавычку f-строки.
Прогон досчитал всё, два часа карты и четырёх кандидатов, и покрасился
в красное на уборке. Синтаксис проверяется за миллисекунды, а узнавать
о нём через два часа счёта дорого.

Проверяется только разбор, а не исполнение: тетради ходят к видеокарте
и к датасетам Kaggle, которых здесь нет.
"""
from __future__ import annotations

import json
import pathlib

import pytest

ТЕТРАДИ = sorted((pathlib.Path(__file__).resolve().parents[1]
                  / "notebooks").glob("*.ipynb"))


def код_ячейки(источник: list[str]) -> str:
    """Исходник ячейки без строк магии: `!nvidia-smi` питон не разберёт.

    Команда оболочки бывает длинной и продолжается на следующих строках
    через обратный слэш. Выбросить одну первую строку нельзя: продолжение
    останется и разберётся как питон с лишним отступом. Пустая строка
    посреди такой команды цепочку не обрывает: редакторы тетрадей иногда
    оставляют её между строками одной команды.
    """
    строки, оболочка = [], False
    for с in источник:
        if оболочка and not с.strip():
            continue
        if оболочка or с.lstrip().startswith(("!", "%")):
            оболочка = с.rstrip("\n").endswith("\\")
            continue
        строки.append(с)
    return "".join(строки)


@pytest.mark.parametrize("путь", ТЕТРАДИ, ids=lambda p: p.name)
def test_ячейки_компилируются(путь: pathlib.Path) -> None:
    тетрадь = json.loads(путь.read_text(encoding="utf-8"))
    for номер, ячейка in enumerate(тетрадь["cells"]):
        if ячейка.get("cell_type") != "code":
            continue
        compile(код_ячейки(ячейка["source"]), f"{путь.name}, ячейка {номер}", "exec")


def test_тетради_нашлись() -> None:
    assert ТЕТРАДИ, "в notebooks/ нет ни одной тетради: проверять нечего"
