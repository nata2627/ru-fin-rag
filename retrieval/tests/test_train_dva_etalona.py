@pytest.mark.data
def test_у_каждого_вопроса_выборки_e5_два_разных_эталона():
    if not ВЫБОРКА.exists():
        pytest.skip("выборки E5 нет: её считает шаг 4 на Kaggle")
    вопросы = read_jsonl(str(ВЫБОРКА))
    без_второго = [q["query_id"] for q in вопросы if not q.get("gold_chunk_id_2")]
    assert без_второго == [], f"{len(без_второго)} вопросов E5 без второго эталона"
    совпали = [q["query_id"] for q in вопросы
               if q["gold_chunk_id"] == q["gold_chunk_id_2"]]
