ROOT = pathlib.Path(__file__).resolve().parents[1]
ВЫБОРКА = ROOT / "data" / "queries" / "synthetic_train_e5_filtered.jsonl"

ТЕКСТЫ = {"590-П_28062017#0001": "Кредитная организация оценивает кредитный риск.",
          "590-П_28062017#0002": "Профессиональное суждение выносится по анализу.",
          "590-П_28062017#0007": "Резерв формируется по категории качества.",
          "254-П_26032004#0003": "Ссуды группируются в портфели однородных ссуд.",
          "447-П_22122014#0005": "Куратор страховой организации назначается на срок."}

СПЛИТ = {"gruppy": {S.TRAIN: ["590-П_28062017", "254-П_26032004"],
                    S.DEV: ["447-П_22122014"],
                    S.TEST_LIVE: [], S.TEST_KIND: [], S.TEST_UNSEEN: []}}


def вопрос(qid: str, gold: str, gold_2: str | None = None) -> dict:
    q = {"query_id": qid, "text": "Как оценивается риск и как формируется резерв?",
         "gold_chunk_id": gold}
    if gold_2:
        q["gold_chunk_id_2"] = gold_2
    return q


def строка(qid: str, gold: str, номер: int = 1) -> TrainPair:
    return TrainPair(query_id=qid, anchor="query: ?", positive="passage: " + gold,
                     gold_chunk_id=gold, act_id=gold.split("#")[0], gold_no=номер)


def лог(p: float) -> float:
    return math.log(p / (1 - p))


# ---- разворот пары в две строки ----

def test_пара_разворачивается_в_две_строки_с_общим_номером_вопроса():
    q = вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003")
    pairs, stats = build_pairs([q], ТЕКСТЫ, two_positives=True)
    assert [p.query_id for p in pairs] == ["tr1", "tr1"]
    assert [p.gold_no for p in pairs] == [1, 2]
    assert [p.gold_chunk_id for p in pairs] == ["590-П_28062017#0001",
                                                "254-П_26032004#0003"]
    assert pairs[0].anchor == pairs[1].anchor
    assert pairs[1].positive == "passage: " + ТЕКСТЫ["254-П_26032004#0003"]
    assert pairs[1].act_id == "254-П_26032004"
    assert stats["вторых эталонов"] == 1
    assert stats["собрано пар"] == 2


def test_без_ключа_второй_эталон_в_обучение_не_идет():
    """Прежний путь обязан остаться прежним: выборки с одним эталоном
    обучаются как раньше, и нулевая точка воспроизводится."""
    q = вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003")
    pairs, stats = build_pairs([q], ТЕКСТЫ)
    assert len(pairs) == 1
    assert pairs[0].gold_chunk_id == "590-П_28062017#0001"
    assert pairs[0].gold_no == 1
    assert stats["вторых эталонов"] == 0


def test_вопрос_без_второго_эталона_дает_одну_строку():
    """Выборки можно смешивать, и вопрос прежнего вида не обязан обзаводиться
    второй строкой из ничего."""
    pairs, stats = build_pairs(
        [вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003"),
         вопрос("tr2", "590-П_28062017#0002")], ТЕКСТЫ, two_positives=True)
    assert len(pairs) == 3
    assert stats["вторых эталонов"] == 1
    assert [p.query_id for p in pairs] == ["tr1", "tr1", "tr2"]


def test_без_второго_эталона_в_нарезке_выбрасывается_весь_вопрос():
    """Одна строка пары без второй это обычный однофрагментный вопрос,
    и он не отличался бы в наборе ничем, кроме того, что опыт на нем
    меряет не то, что объявлено."""
    pairs, stats = build_pairs(
        [вопрос("tr1", "590-П_28062017#0001", "999-П_01012000#0001")],
        ТЕКСТЫ, two_positives=True)
    assert pairs == []
    assert stats["эталона нет в нарезке"] == 1


def test_повтор_вопроса_не_удваивает_пару():
    q = вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003")
    pairs, stats = build_pairs([q, q], ТЕКСТЫ, two_positives=True)
    assert len(pairs) == 2
    assert stats["повтор вопроса"] == 1


