# ---- негативы ----

ПРАВИЛА = NegativeRules(max_score=0.5, absolute_margin=0.10, drop_same_act=True,
                        per_query=2)


def запись(кандидаты, второй: str | None = None, gold_p: float = 0.95) -> dict:
    rec = {"query_id": "tr1", "gold_chunk_id": "590-П_28062017#0001",
           "gold_score": лог(gold_p)}
    if второй:
        rec["gold_chunk_id_2"] = второй
        rec["gold_score_2"] = лог(0.90)
    rec["candidates"] = [[c, лог(p)] for c, p in кандидаты]
    return rec


def test_второй_эталон_не_становится_негативом():
    """Он правильный ответ на этот же вопрос. Негативом он учит модель
    отталкивать правильный ответ, и ни в одной из двух строк пары
    его быть не должно: негативы у строк общие."""
    rec = запись([("254-П_26032004#0003", 0.02), ("300-П_01012020#0005", 0.03)],
                 второй="254-П_26032004#0003")
    pick = pick_negatives(rec, ПРАВИЛА)
    assert pick.negatives == ["300-П_01012020#0005"]
    assert pick.dropped[ВТОРОЙ_ЭТАЛОН] == 1
    assert ЭТАЛОН not in pick.dropped


def test_акт_второго_эталона_исключается_так_же_как_акт_первого():
    """Фрагменты акта нарезаны с перекрытием 15%: сосед второго эталона
    содержит часть его текста и как негатив почти всегда ложный."""
    rec = запись([("254-П_26032004#0004", 0.02), ("300-П_01012020#0005", 0.03)],
                 второй="254-П_26032004#0003")
    pick = pick_negatives(rec, ПРАВИЛА)
    assert pick.negatives == ["300-П_01012020#0005"]
    assert pick.dropped[ТОТ_ЖЕ_АКТ] == 1


def test_у_вопроса_с_одним_эталоном_отсечка_прежняя():
    rec = запись([("254-П_26032004#0003", 0.02), ("300-П_01012020#0005", 0.03)])
    pick = pick_negatives(rec, ПРАВИЛА)
    assert pick.negatives == ["254-П_26032004#0003", "300-П_01012020#0005"]
    assert ВТОРОЙ_ЭТАЛОН not in pick.dropped


def test_строки_пары_получают_одни_негативы():
    """Негативы отобраны по вопросу, а не по строке: оба эталона исключены
    из них разом, и разводить строки по разным спискам нечему."""
    pairs, _ = build_pairs(
        [вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003")],
        ТЕКСТЫ, two_positives=True)
    негативы = {"tr1": ["590-П_28062017#0007", "447-П_22122014#0005"]}
    cols = as_dataset(pairs, негативы, ТЕКСТЫ, per_query=2)
    assert len(cols["anchor"]) == 2
    assert cols["negative_1"][0] == cols["negative_1"][1]


# ---- сборка батча ----

def ключи_пар(вопросов: int) -> list[set]:
    строки = [строка(f"tr{i}", f"590-П_28062017#{2 * i:04d}", номер)
              for i in range(вопросов) for номер in (1, 2)]
    return row_keys(строки)


def test_два_позитива_одного_вопроса_не_в_одном_батче():
    ключи = ключи_пар(300)
    план = plan_batches(ключи, batch_size=128, seed=13)
    for батч in план:
        вопросы = [k for i in батч for k in ключи[i] if k[0] == ВОПРОС]
        assert len(вопросы) == len(set(вопросы))


def test_каждая_строка_попадает_ровно_в_один_батч():
    ключи = ключи_пар(300)
    план = plan_batches(ключи, batch_size=128, seed=13)
    разложено = [i for батч in план for i in батч]
    assert sorted(разложено) == list(range(len(ключи)))
    assert all(len(батч) <= 128 for батч in план)


def test_число_батчей_не_зависит_от_перемешивания():
    """Trainer считает число шагов по длине загрузчика один раз, до первой
    эпохи. Плавающая длина сделала бы «две эпохи» не совсем двумя."""
    ключи = ключи_пар(300)
    длины = {len(plan_batches(ключи, 128, seed=13, epoch=э)) for э in range(5)}
    assert длины == {-(-len(ключи) // 128)}


def test_эпоха_меняет_раскладку_а_семя_ее_повторяет():
    """Во вторую эпоху у вопроса обязаны быть другие негативы, иначе вторая
    эпоха повторяет первую. При том же семени и той же эпохе раскладка
    должна совпасть: иначе прогон не воспроизводится."""
    ключи = ключи_пар(50)
    первая = plan_batches(ключи, 16, seed=13, epoch=0)
    assert первая == plan_batches(ключи, 16, seed=13, epoch=0)
    assert первая != plan_batches(ключи, 16, seed=13, epoch=1)


def test_фрагмент_не_бывает_позитивом_и_негативом_в_одном_батче():
    """То, что делал сэмплер NO_DUPLICATES: фрагмент, попавший в батч
    позитивом одной строки и негативом другой, служит сам себе негативом."""
    строки = [строка("tr1", "590-П_28062017#0001"),
              строка("tr2", "590-П_28062017#0002")]
    негативы = {"tr1": ["254-П_26032004#0003"], "tr2": ["590-П_28062017#0001"]}
    ключи = row_keys(строки, негативы, per_query=1)
    план = plan_batches(ключи, batch_size=8, seed=13)
    assert sorted(len(б) for б in план) == [1, 1]


def test_выборка_меньше_батча_все_равно_разводит_пару():
    """Корзина добавляется сверх расчета: при выборке в две строки корзина
    одна, а положить в нее оба позитива нельзя."""
    план = plan_batches(ключи_пар(1), batch_size=64, seed=13)
    assert len(план) == 2


def test_батч_меньше_одной_строки_это_отказ():
    with pytest.raises(ValueError, match="батч меньше"):
        plan_batches(ключи_пар(2), batch_size=0)


def test_ключи_считаются_по_тем_же_строкам_что_и_набор():
    """Строка без нужного числа негативов в набор не идет. Если ключи
    посчитать по всем строкам, номера разъедутся со строками, и батчи
    соберутся по чужим номерам вопросов."""
    pairs, _ = build_pairs(
        [вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003"),
         вопрос("tr2", "590-П_28062017#0002")], ТЕКСТЫ, two_positives=True)
    негативы = {"tr1": ["590-П_28062017#0007", "447-П_22122014#0005"], "tr2": []}
    cols = as_dataset(pairs, негативы, ТЕКСТЫ, per_query=2)
    ключи = batch_keys(B, pairs, негативы)
    assert len(ключи) == len(cols["anchor"]) == 2
    assert all((ВОПРОС, "tr1") in k for k in ключи)
    assert (ФРАГМЕНТ, "590-П_28062017#0007") in ключи[0]


def test_без_негативов_ключи_по_всем_строкам():
    pairs, _ = build_pairs(
        [вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003")],
        ТЕКСТЫ, two_positives=True)
    ключи = batch_keys(A, pairs, None)
    assert ключи == [{(ВОПРОС, "tr1"), (ФРАГМЕНТ, "590-П_28062017#0001")},
                     {(ВОПРОС, "tr1"), (ФРАГМЕНТ, "254-П_26032004#0003")}]


# ---- сэмплер и подмена сборки ----

class Набор:
    """Набор данных подменён: сэмплеру нужны длина и имена столбцов."""

    def __init__(self, строк: int, столбцы: list[str]) -> None:
        self.строк = строк
        self.column_names = столбцы

    def __len__(self) -> int:
        return self.строк


def test_сэмплер_знает_свою_длину_и_меняет_раскладку_по_set_epoch():
    """Длину `Trainer` спрашивает один раз, до первой эпохи, и считает по ней
    число шагов. Раскладка при этом обязана меняться: иначе вторая эпоха
    повторяет первую теми же негативами."""
    pytest.importorskip("torch")
    from rufin.training.batching import make_grouped_sampler

    сэмплер = make_grouped_sampler(ключи_пар(50), batch_size=16, seed=13)
    первая = list(сэмплер)
    assert len(сэмплер) == len(первая) == 7
    сэмплер.set_epoch(1)
    вторая = list(сэмплер)
    assert вторая != первая
    assert len(сэмплер) == len(вторая) == 7


def test_эпоха_двигается_и_без_вызова_set_epoch():
    """Позовет ли библиотека `set_epoch` на батч-сэмплере, зависит от версии
    и от того, как `accelerate` обернул загрузчик, и проверить это можно
    только на карте. Не позовет, значит вторая эпоха пошла бы той же
    раскладкой, а по числам обучения этого не видно."""
    pytest.importorskip("torch")
    from rufin.training.batching import make_grouped_sampler

    ключи = ключи_пар(50)
    сэмплер = make_grouped_sampler(ключи, batch_size=16, seed=13)
    эпохи = [list(сэмплер) for _ in range(3)]
    assert эпохи[0] != эпохи[1] != эпохи[2]
    assert {len(э) for э in эпохи} == {7}
    for раскладка in эпохи:
        for батч in раскладка:
            вопросы = [k for i in батч for k in ключи[i] if k[0] == ВОПРОС]
            assert len(вопросы) == len(set(вопросы))


def test_раскладка_другой_длины_не_принимается():
    """Число шагов посчитано по длине первой раскладки. Раскладка на батч
    длиннее означала бы, что последний батч эпохи не состоится."""
    pytest.importorskip("torch")
    from rufin.training.batching import make_grouped_sampler

    сэмплер = make_grouped_sampler(ключи_пар(1), batch_size=64, seed=13)
    первая = list(сэмплер)
    assert len(первая) == 2
    сэмплер.батчей = 3
    assert list(сэмплер) == первая


def обучатель(ключи):
    """Обучатель без запуска: ему нужны только правило сборки и настройки.

    Поднимать настоящий `SentenceTransformerTrainer` значило бы поднимать
    модель, а проверяется здесь не обучение, а то, какому набору данных
    достается подмена сборки батча.
    """
    from sentence_transformers.training_args import BatchSamplers

    from rufin.training.batching import make_grouped_trainer

    class Настройки:
        batch_sampler = BatchSamplers.BATCH_SAMPLER

    Обучатель = make_grouped_trainer(ключи, seed=13)
    это = Обучатель.__new__(Обучатель)
    это.args = Настройки
    return это


def test_подмена_сборки_достается_набору_контрастива():
    pytest.importorskip("sentence_transformers")
    сэмплер = обучатель(ключи_пар(8)).get_batch_sampler(
        Набор(16, ["anchor", "positive"]), 4, False)
    assert type(сэмплер).__name__ == "GroupedBatchSampler"
    assert len(сэмплер) == 4


def test_набор_дистилляции_собирается_библиотечным_сэмплером():
    """У дистилляции строка на вопрос, разводить там нечего, а дедупликация
    по восьми текстам строки выбросила бы половину батча."""
    pytest.importorskip("sentence_transformers")
    сэмплер = обучатель(ключи_пар(8)).get_batch_sampler(
        Набор(16, ["anchor", "doc_1"]), 4, False)
    assert type(сэмплер).__name__ != "GroupedBatchSampler"


# ---- дистилляция ----

def test_в_дистилляции_у_второй_строки_своя_оценка_учителя():
    """У пары две оценки учителя. Подстановка первой во вторую строку
    испортила бы распределение, которое ученик повторяет, и по лоссу
    этого не видно."""
    pairs, _ = build_pairs(
        [вопрос("tr1", "590-П_28062017#0001", "254-П_26032004#0003")],
        ТЕКСТЫ, two_positives=True)
    rec = запись([("590-П_28062017#0007", 0.3)], второй="254-П_26032004#0003")
    cols = build_distill_columns(pairs, {"tr1": rec}, ТЕКСТЫ, docs=2, scale="logit")
    assert len(cols["anchor"]) == 2
    assert cols["label"][0][0] == pytest.approx(лог(0.95))
    assert cols["label"][1][0] == pytest.approx(лог(0.90))


