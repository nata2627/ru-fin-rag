"""Два эталона у одного вопроса: разворот в строки, негативы, сборка батча.

Опыт E5 учит на вопросах, ответ на которые требует двух фрагментов.
Правило объявлено до прогона (S26, пункт 4): пара идет двумя строками
обучающей выборки, и два позитива одного вопроса не попадают в один
батч. Контрастивная функция потерь считает негативами позитивы остальных
строк батча, поэтому две строки одного вопроса рядом означают указание
отталкивать правильный ответ.

Проверять это числами обучения нельзя: лосс при такой поломке падает
как положено, а dev проседает без всякой видимой причины. Поэтому
правило проверяется здесь, на выдуманных данных, и отдельно проверяется
то, что прежний путь с одним эталоном не тронут: нулевая точка рецепта
обязана воспроизвестись побайтно.
"""
