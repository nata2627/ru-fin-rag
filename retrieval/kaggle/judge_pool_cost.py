#!/usr/bin/env python3
"""Чем размечать весь пул: квотой Kaggle или арендованной картой.

Считается по замеренной скорости, а не по прикидке: скорость каждого судьи
берется из метаданных его прогона (`kaggle/judge_probe_table.py` собирает их
в одну таблицу). Цена аренды берется из поиска предложений vast.ai на дату
замера и подписана датой: предложения живут часами, а не неделями.

Чего в этом файле нет и почему. Скорости на арендованной карте нет ни одной:
24.10 из четырех арендованных машин ни одна не досчитала (две не отдали карту
контейнеру, одна осталась без ssh в образе, одной не хватило времени на
образ). Поэтому столбец аренды помечен как прогноз, а множитель скорости
назван отдельной строкой со своим основанием. Прогноз и замер в одну колонку
не ставятся.
"""
from __future__ import annotations

import argparse
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

POOLS = {"весь пул глубины 50": 40134, "ядро первой десятки": 4134}

# Квота Kaggle: 30 ч в неделю на видеокарту, сессия не длиннее 12 ч.
КВОТА_НЕДЕЛИ_Ч = 30.0
СЕССИЯ_Ч = 12.0

# Предложения vast.ai, снятые 24.10.2026 поиском без ключа. Множитель
# скорости против одной T4 это НЕ замер: он взят по отношению пропускной
# способности fp16 и памяти, и подписан как прогноз. AWQ в vLLM требует
# вычислительной способности не ниже 75, поэтому P100 (60) и V100 (70)
# в список не входят вовсе, хотя они самые дешевые.
АРЕНДА = [
    {"карта": "RTX A4000 16 ГБ", "способность": 86, "цена_ч": 0.0729,
     "множитель_к_T4": 1.5, "где": "Japan"},
    {"карта": "RTX 2080 Ti 22 ГБ", "способность": 75, "цена_ч": 0.0978,
     "множитель_к_T4": 2.0, "где": "New York"},
    {"карта": "RTX 3090 24 ГБ", "способность": 86, "цена_ч": 0.1222,
     "множитель_к_T4": 3.0, "где": "Quebec"},
]

ОТКАЗЫ_АРЕНДЫ = [
    "57514110 RTX 2080 Ti 0,0978 $/ч: образ 25 ГБ не приехал, 0,047 $",
    "57526932 RTX 3090 0,1283 $/ч: хозяин не отдал карту (CDI), 0,0009 $",
    "57527074 Q RTX 5000 0,1044 $/ч: в образе нет ssh-сервера, 0,0067 $",
    "57527884 RTX A4000 0,0978 $/ч: хозяин не отдал карту (CDI), 0,0072 $",
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", default="data/results/judge_probe_table.json")
    ap.add_argument("--result", default="data/results/judge_pool_cost.json")
    ap.add_argument("--report", default="docs/raw/judge_pool_cost.txt")
    args = ap.parse_args()

    with open(os.path.join(ROOT, args.table), encoding="utf-8") as f:
        table = json.load(f)

    судьи = []
    for r in table["судьи"]:
        if "повтор" in r["судья"]:
            continue
        годен = r["не разобрано"] == 0
        строка = {
            "судья": r["судья"], "машина": r["машина"], "пар/с": r["пар/с"],
            "не разобрано": r["не разобрано"], "из": r["из"],
            "формат держит": годен,
            "оценки 0/1/2": [r["оценка 0"], r["оценка 1"], r["оценка 2"]],
        }
        for имя, пар in POOLS.items():
            строка[f"{имя}, часов"] = round(пар / r["пар/с"] / 3600, 2)
        судьи.append(строка)

    # Цена аренды считается только для судей, которые считались на T4:
    # множитель объявлен как отношение к одной T4, и к карте RTX 3070 он
    # не относится.
    аренда = []
    for r in судьи:
        if not r["машина"].startswith("Tesla T4"):
            continue
        карты_в_прогоне = 2 if "x2" in r["машина"] else 1
        for о in АРЕНДА:
            # Скорость на одной арендованной карте: прогон на двух T4 сначала
            # приводится к одной карте, иначе множитель применялся бы к
            # скорости, которую дали две карты, а арендуется одна.
            на_одной_T4 = r["пар/с"] / карты_в_прогоне
            прогноз = на_одной_T4 * о["множитель_к_T4"]
            for имя, пар in POOLS.items():
                часов = пар / прогноз / 3600
                аренда.append({
                    "судья": r["судья"], "карта": о["карта"],
                    "где": о["где"], "цена_ч": о["цена_ч"],
                    "пул": имя, "пар": пар,
                    "скорость, пар/с (прогноз)": round(прогноз, 3),
                    "часов (прогноз)": round(часов, 1),
                    "долларов (прогноз)": round(часов * о["цена_ч"], 2),
                })

    # Путь «голосование фильтром» (решение Наталии 24.10): весь пул размечает
    # первый судья, второй проходит только пары, где первый сказал «да» хотя
    # бы на один вопрос. Экономия считается по доле, ЗАМЕРЕННОЙ на листе
    # пробы из 150 пар, а не на пуле: лист собран стратами и пулу не
    # пропорционален, поэтому доля на пуле заранее неизвестна.
    фильтр = []
    пул = POOLS["весь пул глубины 50"]
    for первый in table["судьи"]:
        # Судья, который не держит формат, в путь не ставится: 7B не
        # разобрался на 83 парах из 150, и доля «да» у него считалась бы по
        # той трети, что уцелела. Порог назван числом, а не на глаз.
        if "повтор" in первый["судья"] or первый["не разобрано"] > 15:
            continue
        доля = первый["на второго судью"] / первый["размечено первым"]
        for второй in table["судьи"]:
            if "повтор" in второй["судья"] or второй["не разобрано"] > 15:
                continue
            if второй["судья"] == первый["судья"]:
                continue
            пар_второму = round(пул * доля)
            ч1 = пул / первый["пар/с"] / 3600
            ч2 = пар_второму / второй["пар/с"] / 3600
            фильтр.append({
                "первый": первый["судья"], "второй": второй["судья"],
                "машина первого": первый["машина"],
                "машина второго": второй["машина"],
                "доля на второго (замер на 150 парах)": round(доля, 3),
                "на второго судью": первый["на второго судью"],
                "не проверит никто": первый["не проверит никто"],
                "разобрал первый": первый["размечено первым"],
                "пар второму на пуле (оценка по этой доле)": пар_второму,
                "часов первым": round(ч1, 1), "часов вторым": round(ч2, 1),
                "часов всего": round(ч1 + ч2, 1),
            })

    out = {"дата": "24.10.2026", "пулы": POOLS,
           "квота Kaggle, часов в неделю": КВОТА_НЕДЕЛИ_Ч,
           "предел сессии Kaggle, часов": СЕССИЯ_Ч,
           "замерено": судьи,
           "прогноз аренды": аренда,
           "путь голосования фильтром": фильтр,
           "множитель скорости к одной T4 это прогноз, не замер": True,
           "ни одна арендованная машина 24.10 не досчитала": ОТКАЗЫ_АРЕНДЫ}
    with open(os.path.join(ROOT, args.result), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    L = ["чем размечать пул: квота Kaggle против аренды, 24.10.2026", "",
         f"пулы: {', '.join(f'{k} {v} пар' for k, v in POOLS.items())}",
         f"квота Kaggle {КВОТА_НЕДЕЛИ_Ч:.0f} ч в неделю, сессия не длиннее "
         f"{СЕССИЯ_Ч:.0f} ч", "",
         "ЗАМЕРЕНО (скорость из метаданных прогона):",
         f"   {'судья':<34} {'машина':<18} {'пар/с':>6} {'не разобр':>10} "
         f"{'пул, ч':>8} {'ядро, ч':>8}"]
    for r in судьи:
        L.append(f"   {r['судья']:<34} {r['машина']:<18} {r['пар/с']:>6.3f} "
                 f"{str(r['не разобрано']) + ' из ' + str(r['из']):>10} "
                 f"{r['весь пул глубины 50, часов']:>8.2f} "
                 f"{r['ядро первой десятки, часов']:>8.2f}")
    L += ["", "ПРОГНОЗ аренды (множитель к одной T4 это прогноз, не замер):",
          f"   {'судья':<26} {'карта':<20} {'$/ч':>7} {'пул':<24} "
          f"{'ч':>6} {'$':>6}"]
    for a in аренда:
        L.append(f"   {a['судья'][:26]:<26} {a['карта']:<20} "
                 f"{a['цена_ч']:>7.4f} {a['пул']:<24} "
                 f"{a['часов (прогноз)']:>6.1f} {a['долларов (прогноз)']:>6.2f}")
    L += ["", "ПУТЬ «ГОЛОСОВАНИЕ ФИЛЬТРОМ»: первый судья по всему пулу,",
          "второй только там, где первый сказал «да» хотя бы на один вопрос.",
          "Доля замерена на листе из 150 пар, пулу он не пропорционален:",
          f"   {'первый':<26} {'второй':<26} {'доля':>6} {'ч1':>6} {'ч2':>6} "
          f"{'всего ч':>8}"]
    for f_ in фильтр:
        L.append(f"   {f_['первый'][:26]:<26} {f_['второй'][:26]:<26} "
                 f"{f_['доля на второго (замер на 150 парах)']:>6.3f} "
                 f"{f_['часов первым']:>6.1f} {f_['часов вторым']:>6.1f} "
                 f"{f_['часов всего']:>8.1f}")
    L += ["", "что фильтр НЕ проверяет, и это ограничение метода, а не недосмотр:"]
    for первый in {f_["первый"]: f_ for f_ in фильтр}.values():
        L.append(f"   первым {первый['первый'][:34]:<34} второму ушло "
                 f"{первый['на второго судью']} из {первый['разобрал первый']}, "
                 f"не проверит никто {первый['не проверит никто']} из "
                 f"{первый['разобрал первый']}")
    L += ["", "почему в списке нет самых дешевых карт:",
          "   AWQ в vLLM требует вычислительной способности не ниже 75",
          "   (проверено в коде движка 0.32.0, auto_awq.get_min_capability).",
          "   Tesla P100 это 60, Tesla V100 это 70, то есть 0,0363 и 0,0822 $/ч",
          "   для этих весов не годятся вовсе.", "",
          "ни одна арендованная машина 24.10 не досчитала:"]
    for о in ОТКАЗЫ_АРЕНДЫ:
        L.append(f"   {о}")
    with open(os.path.join(ROOT, args.report), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
