"""Ворота по живым вопросам: пускать ли конфигурацию дальше.

Зачем это нужно, видно из этапа 3. Рецепт дообучения отбирался по трёмстам
синтетическим вопросам, девять решений «принять или отклонить» подряд,
и все они оптимизировали жанр, который на живых вопросах не переносится.
Итог известен: прибавка 0,149 там, где вопрос писала модель, и просадка
0,062 там, где писали люди.

Разделение обязанностей, которое из этого следует:

* **синтетический dev ранжирует** кандидатов, его триста вопросов и нужны
  для того, чтобы отличить рецепт от рецепта;
* **живые вопросы работают воротами**, а не селектором. Ворота отвечают
  на один вопрос, не стало ли хуже настоящему пользователю, и применяются
  считанные разы.

Разница не косметическая. Селектор, применённый девять раз к набору
из 142 запросов, подогнал бы выбор под шум этого набора. Ворота,
применённые три-четыре раза, этого не делают, и каждое применение
записывается в журнал, чтобы их число было видно в отчёте.

Правило объявляется до запуска и здесь же зафиксировано. Менять его
после того, как числа увидены, нельзя: это превращает ворота в селектор.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .metrics import Interval, paired_diff_ci

# Допуск. Просадка меньше него объявлена не имеющей значения, и объявлено
# это до того, как увидены числа. Величина выбрана так: набор из 142 живых
# вопросов различает разницу примерно от 0,03, а прибавка, ради которой
# затевается дообучение, измеряется десятыми. Потерять две сотых на живых
# ради заметного прироста на остальном допустимо; потерять больше — нет.
ДОПУСК = 0.02


@dataclass(frozen=True)
class Вердикт:
    """Решение ворот по одной конфигурации."""
    кандидат: str
    эталон: str
    запросов: int
    среднее_кандидата: float
    среднее_эталона: float
    разница: Interval
    p: float
    принят: bool
    причина: str

    @property
    def установлена(self) -> bool:
        """Накрывает ли интервал разности ноль."""
        return self.разница.hi < 0 or self.разница.lo > 0

    @property
    def различимое(self) -> float:
        """Какую разницу этот набор вообще способен обнаружить."""
        return (self.разница.hi - self.разница.lo) / 2

    def __str__(self) -> str:
        знак = "ПРИНЯТ" if self.принят else "ОТКЛОНЁН"
        уст = "установлена" if self.установлена else "не установлена"
        return (f"{self.кандидат} против {self.эталон}: "
                f"{self.среднее_эталона:.3f} -> {self.среднее_кандидата:.3f}, "
                f"разница {self.разница.mean:+.3f} "
                f"[{self.разница.lo:+.3f}; {self.разница.hi:+.3f}] "
                f"p={self.p:.3f}, {уст} — {знак}, {self.причина}")


def решить(кандидат: np.ndarray, эталон: np.ndarray, *,
           имя: str = "кандидат", имя_эталона: str = "эталон",
           допуск: float = ДОПУСК, seed: int = 0) -> Вердикт:
    """Пропустить ли кандидата. Значения метрики по каждому живому запросу.

    **Правило, зафиксированное до первого применения.** Кандидат отклоняется,
    если точечная оценка разницы с эталоном ниже минус допуска. Иначе принят.

    Почему решает точечная оценка, а не интервал. Первая версия правила
    отклоняла всё, у чего интервал целиком ниже нуля, и тесты показали,
    во что это выливается: кандидат с устойчивой просадкой в одну тысячную
    отклонялся как «установленная просадка». Устойчивость и величина это
    разные вещи, и ворота должны смотреть на вторую.

    Почему не строгая проверка на неухудшение, где требуется, чтобы нижняя
    граница интервала была выше минус допуска. Она статистически правильнее,
    но на 142 живых вопросах её не пройдёт почти ничто: полуширина интервала
    около 0,03, и чтобы доказать неухудшение на 0,02, нужна точечная оценка
    выше плюс 0,015. Отклонять по такому правилу значит отклонять всё подряд.
    Поэтому ворота здесь прагматические, а не доказательные, и это сказано
    прямо, а не спрятано.

    Правило несимметрично нарочно. Прироста на живых вопросах ворота
    не требуют, им достаточно отсутствия заметного ухудшения. Установленность
    разницы печатается в вердикте, но на решение не влияет.
    """
    разница, p = paired_diff_ci(кандидат, эталон, seed=seed)
    общих = int((~(np.isnan(кандидат) | np.isnan(эталон))).sum())
    if разница.mean < -допуск:
        принят = False
        причина = f"просадка {-разница.mean:.3f} больше допуска {допуск:.2f}"
    else:
        принят = True
        причина = f"просадка в пределах допуска {допуск:.2f}"
    return Вердикт(имя, имя_эталона, общих,
                   float(np.nanmean(кандидат)), float(np.nanmean(эталон)),
                   разница, p, принят, причина)
