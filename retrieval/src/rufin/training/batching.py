"""Сборка батча, когда у вопроса два эталона (S26, пункт 4).

Опыт E5 учит на вопросах, ответ на которые требует двух фрагментов сразу.
Пара идет двумя строками обучающей выборки, у строк общий номер вопроса,
и отсюда требование к сборке батча, объявленное до прогона.

**Почему две строки одного вопроса нельзя класть в один батч.**
Контрастивная функция потерь считает негативами позитивы остальных строк
батча: при батче 128 у каждого вопроса 127 негативов, и в этом весь ее
прием. Две строки одного вопроса в одном батче означают, что второй
правильный ответ приходит модели как негатив, то есть она получает
указание отталкивать правильный ответ. Лосс при этом падает как
положено, и по числам поломку не видно: модель учится обратному тому,
ради чего затеян опыт.

**Ключ строки это номер вопроса и идентификаторы ее фрагментов.** В один
батч не идут строки, у которых есть общий ключ. Номер вопроса разводит
два позитива одной пары, а идентификаторы эталона и негативов повторяют
то, что делал сэмплер `NO_DUPLICATES`: фрагмент, попавший в батч и
позитивом одной строки, и негативом другой, служит сам себе негативом.
Идентификаторы, а не тексты: они короткие, их сравнение не зависит от
нарезки и от того, какой хеш у строки в этом процессе, поэтому раскладка
батчей воспроизводится от прогона к прогону.

**Число батчей за эпоху не зависит от перемешивания.** Строки
раскладываются по корзинам известного числа, а не набираются жадно
подряд: `Trainer` считает число шагов по длине загрузчика один раз,
до первой эпохи, и плавающая длина сделала бы «две эпохи» не совсем
двумя эпохами.
"""
from __future__ import annotations

import random
import zlib
from collections.abc import Mapping, Sequence

from .pairs import TrainPair

ВОПРОС = "вопрос"
ФРАГМЕНТ = "фрагмент"


def row_keys(rows: Sequence[TrainPair], negatives: Mapping[str, list[str]] | None = None,
             per_query: int = 2) -> list[set[tuple[str, str]]]:
    """Ключи строк набора в том же порядке, в каком строки лежат в наборе.

    Негативы берутся те же и в том же числе, что попали в набор: ключ
    должен описывать строку, которая поедет в батч, а не ту, которая
    могла бы.
    """
    out: list[set[tuple[str, str]]] = []
    for row in rows:
        ключи = {(ВОПРОС, row.query_id), (ФРАГМЕНТ, row.gold_chunk_id)}
        if negatives is not None:
            ключи |= {(ФРАГМЕНТ, c) for c in negatives.get(row.query_id, [])[:per_query]}
        out.append(ключи)
    return out


def plan_batches(ключи: Sequence[set], batch_size: int, seed: int = 0,
                 epoch: int = 0, drop_last: bool = False) -> list[list[int]]:
    """Разложить строки по батчам так, чтобы общий ключ не встретился дважды.

    Корзин ровно столько, сколько батчей вышло бы при обычном разбиении,
    и строка кладется в самую свободную корзину, где ни одного ее ключа
    еще нет. Порядок строк перемешивается семенем и номером эпохи: вторая
    эпоха обязана давать другие батчи, иначе негативы у вопроса те же, что
    и в первой.

    Корзина добавляется сверх расчета только тогда, когда строку деть
    больше некуда: так бывает на выборке меньше батча, где все корзины
    это одна корзина, а у вопроса два позитива.
    """
    if batch_size < 1:
        raise ValueError(f"размер батча {batch_size}: батч меньше одной строки")
    порядок = list(range(len(ключи)))
    random.Random(seed + epoch).shuffle(порядок)
    корзин = max(1, -(-len(порядок) // batch_size))
    корзины: list[list[int]] = [[] for _ in range(корзин)]
    занято: list[set] = [set() for _ in range(корзин)]
    for i in порядок:
        свои = ключи[i]
        куда, свободнее = -1, 0
        for b, корзина in enumerate(корзины):
            свободно = batch_size - len(корзина)
            if свободно <= свободнее or занято[b] & свои:
                continue
            куда, свободнее = b, свободно
        if куда < 0:
            корзины.append([])
            занято.append(set())
            куда = len(корзины) - 1
        корзины[куда].append(i)
        занято[куда] |= свои
    план = [к for к in корзины if к]
    if drop_last:
        план = [к for к in план if len(к) == batch_size]
    return план


def отпечаток(план: Sequence[Sequence[int]]) -> str:
    """Короткий отпечаток раскладки: по нему в журнале прогона видно, что
    вторая эпоха отличается от первой, и видно, звали ли `set_epoch`."""
    порядок = ",".join(str(i) for батч in план for i in батч)
    return f"{zlib.crc32(порядок.encode()):08x}"


def make_grouped_sampler(ключи: Sequence[set], batch_size: int, drop_last: bool = False,
                         seed: int = 0):
    """Сэмплер батчей по этому правилу. torch импортируется внутри.

    Раскладка считается один раз на эпоху, а не на каждый батч: при
    тринадцати тысячах строк это доли секунды, зато длина известна заранее
    и `Trainer` считает шаги по ней, а не по догадке.

    **Эпоха двигается сама.** Штатный путь это `set_epoch`, его зовет
    библиотека в начале эпохи. Но позовет ли она его на батч-сэмплере,
    зависит от версии и от того, как `accelerate` обернул загрузчик, и
    проверить это можно только на карте. Не позовет, значит вторая эпоха
    пошла бы той же раскладкой: негативы у вопроса повторились бы, а по
    числам этого не видно. Поэтому, пока `set_epoch` не позвали ни разу,
    номером эпохи служит счет проходов по сэмплеру.

    **Длина не меняется.** Свежая раскладка принимается только если число
    батчей совпало с первым: `Trainer` считает шаги по длине загрузчика
    один раз, до первой эпохи. Не совпало, значит эпоха идет прежней
    раскладкой, и об этом печатается строка.
    """
    from torch.utils.data import BatchSampler

    class GroupedBatchSampler(BatchSampler):
        def __init__(self) -> None:
            super().__init__(range(len(ключи)), batch_size, drop_last)
            self.epoch = 0
            self.звали_set_epoch = False
            self.проходов = 0
            self.план = plan_batches(ключи, batch_size, seed, 0, drop_last)
            self.батчей = len(self.план)
            self.эпоха_плана = 0

        def set_epoch(self, epoch: int) -> None:
            self.звали_set_epoch = True
            self.epoch = epoch

        def __iter__(self):
            эпоха = self.epoch if self.звали_set_epoch else self.проходов
            self.проходов += 1
            if эпоха != self.эпоха_плана:
                свежая = plan_batches(ключи, batch_size, seed, эпоха, drop_last)
                if len(свежая) == self.батчей:
                    self.план, self.эпоха_плана = свежая, эпоха
                else:
                    print(f"эпоха {эпоха}: раскладка дала {len(свежая)} батчей "
                          f"вместо {self.батчей}, иду раскладкой эпохи "
                          f"{self.эпоха_плана}: число шагов посчитано по ней",
                          flush=True)
            откуда = "set_epoch" if self.звали_set_epoch else "счет проходов"
            print(f"эпоха {эпоха} ({откуда}): {len(self.план)} батчей, "
                  f"отпечаток раскладки {отпечаток(self.план)}", flush=True)
            return iter(self.план)

        def __len__(self) -> int:
            return len(self.план)

    return GroupedBatchSampler()


def make_grouped_trainer(ключи: Sequence[set], seed: int = 0):
    """Обучатель, который собирает батчи набора `pairs` этим правилом.

    Библиотека зовет `get_batch_sampler` на каждый набор данных отдельно,
    и подменяется только набор контрастива: у дистилляции строка на вопрос,
    и разводить там нечего. Набор узнается по столбцу `positive` и по числу
    строк, а не по порядку вызовов.

    Если имя метода в очередной версии библиотеки изменится, подмена молча
    не случится, а батчи соберутся как раньше: два позитива одного вопроса
    снова окажутся рядом. Поэтому имя проверяется здесь, при сборке, а факт
    подмены печатается.
    """
    from sentence_transformers import SentenceTransformerTrainer

    if not hasattr(SentenceTransformerTrainer, "get_batch_sampler"):
        raise SystemExit(
            "эта версия sentence-transformers не зовет get_batch_sampler: "
            "правило сборки батча (S26, пункт 4) не применилось бы, а два "
            "позитива одного вопроса попали бы в один батч. Обучать нельзя.")

    class GroupedTrainer(SentenceTransformerTrainer):
        def get_batch_sampler(self, dataset, batch_size, drop_last,
                              valid_label_columns=None, generator=None, **kwargs):
            наш = len(dataset) == len(ключи) and "positive" in dataset.column_names
            if not наш:
                return super().get_batch_sampler(dataset, batch_size, drop_last,
                                                 valid_label_columns, generator, **kwargs)
            sampler = make_grouped_sampler(ключи, batch_size, drop_last, seed)
            print(f"батчи собраны правилом двух позитивов: {len(sampler)} батчей "
                  f"по {batch_size} строк, два эталона одного вопроса разведены",
                  flush=True)
            return sampler

    return GroupedTrainer
