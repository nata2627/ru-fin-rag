def test_перебор_дает_ту_же_выдачу_для_половинной_точности():
    # матрицы ветвей нарезки лежат на диске в float16 (263 МБ вместо 526),
    # и поиск обязан читать их без приведения всей матрицы в копию
    from rufin.retrieval.dense import top_k
    rng = np.random.default_rng(7)
    матрица = rng.normal(size=(300, 16))
    матрица /= np.linalg.norm(матрица, axis=1, keepdims=True)
    запросы = матрица[:5] + 0.01 * rng.normal(size=(5, 16))

    точно = top_k(запросы.astype("float32"), матрица.astype("float32"), 10)
    половинно = top_k(запросы.astype("float32"), матрица.astype("float16"), 10)
    assert [[j for j, _ in строка] for строка in точно][0][0] == 0
    # половинная точность меняет оценки в пятом знаке, порядок первых десяти
    # от этого не зависит
    assert ([[j for j, _ in строка] for строка in точно]
            == [[j for j, _ in строка] for строка in половинно])
