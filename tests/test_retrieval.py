def test_редкое_слово_весит_больше_частого(индекс):
    # «резерв» есть в трёх документах из четырёх, «портфель» — в одном.
    # Ключ словаря это основа: индекс собран рабочей токенизацией
    assert индекс.idf[индекс.vocab[stem("портфелю")]] > индекс.idf[индекс.vocab["резерв"]]


def test_отрицательный_вес_заменяется(индекс):
    # у Okapi слово из большинства документов получает отрицательный вес
    # и начинает работать против документов, где оно есть.
    # Ровный ноль при этом законен: на четырех документах слово из двух
    # дает log(2,5) - log(2,5), и заменять такое не на что
    assert индекс.idf.min() >= 0
    assert индекс.idf[индекс.vocab["резерв"]] > 0


