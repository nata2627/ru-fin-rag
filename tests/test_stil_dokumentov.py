"""Публичные документы без длинного тире и без буквы ё.

Правило автора касается всех текстов проекта. Документы части А писались до
него и приведены к нему 28.10.2026 по ее решению, 571 замена тире и 772 замены
буквы. Без этой проверки знак вернется первой же правкой руками, и никто этого
не заметит: в тексте на тысячу строк одно тире глазами не находится.

Три вида участков проверка пропускает намеренно, и каждый по своей причине.
Цитата в ёлочках это чужие или свои слова дословно, правка цитаты это подделка.
Блок кода и вывода программы это сырой вывод прогона, а инструкция разметчику
внутри такого блока обязана совпадать с константой `RUBRIC` дословно, что
держит отдельный тест части А. Блочная цитата это постановка, ее не правят.

Пропуск блоков кода целиком оказался слишком широким: 28.10.2026 линтер каркаса
нашел в них девять строк своих же комментариев со знаком и буквой, то есть
обычный текст, спрятанный за тройной кавычкой. Строки поправлены, а блоки
закрыты последним тестом: внутри них разрешены только названные исключения, и
каждое проверяется делом, а не словом.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЗАЩИТА = [
    re.compile(r"«[^»]*»", re.S),
    re.compile(r"```.*?```", re.S),
    re.compile(r"`[^`\n]+`"),
    re.compile(r"^>.*$", re.M),
]


def документы() -> list[Path]:
    вывод = subprocess.run(
        ["git", "ls-files", "*.md"],
        cwd=КОРЕНЬ,
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    return [КОРЕНЬ / имя for имя in вывод]


def открытые_места(текст: str) -> list[bool]:
    закрыто = [False] * len(текст)
    for шаблон in ЗАЩИТА:
        for м in шаблон.finditer(текст):
            for i in range(м.start(), м.end()):
                закрыто[i] = True
    return закрыто


def находки(знак: str) -> list[str]:
    беда = []
    for путь in документы():
        текст = путь.read_text(encoding="utf-8")
        if знак not in текст:
            continue
        закрыто = открытые_места(текст)
        for м in re.finditer(re.escape(знак), текст):
            if закрыто[м.start()]:
                continue
            строка = текст[: м.start()].count("\n") + 1
            кусок = текст[max(0, м.start() - 30) : м.start() + 30].replace("\n", " ")
            беда.append(f"{путь.relative_to(КОРЕНЬ)}:{строка}: {кусок}")
    return беда


def test_net_dlinnogo_tire() -> None:
    беда = находки("—")
    assert беда == [], "\n".join(беда[:10])


def test_net_bukvy_yo() -> None:
    беда = находки("ё") + находки("Ё")
    assert беда == [], "\n".join(беда[:10])


def test_proverka_vidit_podlozhennyi_znak(tmp_path: Path) -> None:
    """Проверка, которая ничего не ловит, неотличима от опечатки в шаблоне."""
    текст = "обычная строка — с тире\n`код — не считается`\n«цитата — тоже»\n"
    закрыто = открытые_места(текст)
    открытых = [i for i, м in enumerate(закрыто) if not м and текст[i] == "—"]
    assert len(открытых) == 1


ИСКЛЮЧЕНИЯ_В_БЛОКАХ = [
    (
        "retrieval/docs/15-razbor-nomera-akta.md",
        "[а-яёa-z0-9]",
        "буква стоит внутри класса символов выражения, правка меняет само выражение",
    ),
    ("retrieval/docs/ANNOTATION_GUIDE.md", "«общая норма» —", "дословная строка RUBRIC"),
    ("retrieval/docs/ANNOTATION_GUIDE.md", "«часть ответа» —", "дословная строка RUBRIC"),
    ("retrieval/docs/ANNOTATION_GUIDE.md", "«иное» —", "дословная строка RUBRIC"),
]


def строки_в_блоках() -> list[tuple[str, int, str]]:
    найдено = []
    for путь in документы():
        внутри = False
        for номер, строка in enumerate(путь.read_text(encoding="utf-8").split("\n"), 1):
            if строка.lstrip().startswith("```"):
                внутри = not внутри
                continue
            if внутри and ("—" in строка or "ё" in строка or "Ё" in строка):
                найдено.append((str(путь.relative_to(КОРЕНЬ)), номер, строка))
    return найдено


def test_v_blokah_koda_tolko_nazvannye_isklyucheniya() -> None:
    беда = [
        f"{имя}:{номер}: {строка.strip()[:80]}"
        for имя, номер, строка in строки_в_блоках()
        if not any(имя == файл and кусок in строка for файл, кусок, _ in ИСКЛЮЧЕНИЯ_В_БЛОКАХ)
    ]
    assert беда == [], "\n".join(беда[:10])


def test_isklyucheniya_v_blokah_vse_na_meste() -> None:
    """Исключение без причины, проверенной делом, это просто разрешенный знак."""
    рубрика = (КОРЕНЬ / "retrieval/src/rufin/annotation.py").read_text(encoding="utf-8")
    для_рубрики = 0
    for файл, кусок, причина in ИСКЛЮЧЕНИЯ_В_БЛОКАХ:
        assert any(
            имя == файл and кусок in строка for имя, _, строка in строки_в_блоках()
        ), f"исключение {файл} {кусок} больше ни на что не ссылается, его пора убрать"
        if причина == "дословная строка RUBRIC":
            assert кусок in рубрика, f"{кусок} не совпадает с RUBRIC части А"
            для_рубрики += 1
    assert для_рубрики == 3
