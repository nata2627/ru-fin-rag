"""Ворота по живым вопросам.

Правило несимметрично нарочно, и именно это надо защитить тестами:
ворота не требуют прироста, но не пускают просадку, в том числе
неустановленную, если точечная оценка ниже допуска. Поменяй знак
в одном месте, и ворота превратятся в селектор, который подгонит
выбор под шум набора из 142 запросов.
"""
from __future__ import annotations

import numpy as np
import pytest

from rufin.gate import ДОПУСК, решить


def одинаковые(n=120, значение=0.4):
    return np.full(n, значение), np.full(n, значение)


def test_одинаковые_выдачи_проходят():
    a, b = одинаковые()
    в = решить(a, b)
    assert в.принят
    assert в.разница.mean == pytest.approx(0.0)


def test_крупная_просадка_не_проходит():
    в = решить(np.full(120, 0.30), np.full(120, 0.40))
    assert not в.принят
    assert "больше допуска" in в.причина


def test_прирост_проходит():
    assert решить(np.full(120, 0.40), np.full(120, 0.30)).принят


def test_прирост_не_требуется():
    # ворота не селектор: отсутствия заметного ухудшения достаточно
    rng = np.random.default_rng(0)
    b = rng.random(200)
    assert решить(b - 0.001, b).принят


def test_устойчивая_но_крошечная_просадка_проходит():
    # этот случай и сломал первую версию правила: интервал целиком ниже
    # нуля, разница устойчива, но её величина одна тысячная
    в = решить(np.full(200, 0.399), np.full(200, 0.400))
    assert в.установлена, "для теста нужна устойчивая разница"
    assert в.принят


def test_мелкая_просадка_внутри_допуска_проходит():
    assert решить(np.full(120, 0.40 - ДОПУСК / 2), np.full(120, 0.40)).принят


def test_просадка_чуть_меньше_допуска_проходит():
    # ровно на границе проверять нечего: 0,40 минус 0,02 в плавающей точке
    # даёт 0,020000000000000018, и тест проверял бы арифметику, а не правило
    assert решить(np.full(120, 0.40 - ДОПУСК * 0.95), np.full(120, 0.40)).принят


def test_просадка_чуть_больше_допуска_не_проходит():
    assert not решить(np.full(120, 0.40 - ДОПУСК * 1.05), np.full(120, 0.40)).принят


def test_неустановленная_крупная_просадка_не_проходит():
    # интервал накрывает ноль, но точечная оценка хуже допуска.
    # Бремя доказательства на кандидате, а не на живых вопросах
    rng = np.random.default_rng(1)
    b = rng.random(60)
    a = b - 0.05 + rng.normal(0, 0.4, 60)
    в = решить(a, b)
    assert not в.установлена, "для теста нужен интервал, накрывающий ноль"
    assert not в.принят


def test_допуск_настраивается():
    a, b = np.full(120, 0.37), np.full(120, 0.40)
    assert not решить(a, b, допуск=0.01).принят
    assert решить(a, b, допуск=0.05).принят


def test_различимое_падает_с_ростом_набора():
    rng = np.random.default_rng(2)
    мало = решить(rng.random(40), rng.random(40))
    много = решить(rng.random(400), rng.random(400))
    assert много.различимое < мало.различимое


def test_запросы_без_эталона_не_считаются():
    a = np.array([1.0, np.nan, 1.0, 1.0])
    b = np.array([1.0, 1.0, 1.0, np.nan])
    assert решить(a, b).запросов == 2


def test_вердикт_печатается_с_интервалом_и_установленностью():
    s = str(решить(*одинаковые(), имя="кандидат", имя_эталона="эталон"))
    assert "кандидат против эталон" in s
    assert "ПРИНЯТ" in s and "[" in s and "установлена" in s


def test_решение_воспроизводимо_по_зерну():
    rng = np.random.default_rng(3)
    a, b = rng.random(100), rng.random(100)
    assert str(решить(a, b, seed=7)) == str(решить(a, b, seed=7))
