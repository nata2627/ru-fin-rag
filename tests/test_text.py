"""Токенизация сервиса обязана совпадать с частью А до токена.

Сверка выдач (`test_search_matches_part_a.py`) ловит расхождение по итогу, но
говорит про него как про переставленные фрагменты. Эти проверки говорят, что
именно разошлось, и держат те случаи, на которых разбор уже один раз ломался.
"""

from __future__ import annotations

from rufinrag.retrieval.text import split_tokens, stem, tokenize


def test_act_number_stays_one_token():
    # по номеру часто и ищут, разбиение «590» и «п» такой запрос убивает
    assert split_tokens("Положение 590-П о резервах") == ["положение", "590-п", "резервах"]
    assert split_tokens("Закон 86-ФЗ") == ["закон", "86-фз"]


def test_letter_number_stays_one_token():
    """Вторая часть номера из цифр отваливалась до 23.10.2026.

    Письмо «ИН-03-23/109» давало токен «ин», общий у всех информационных
    писем, и три частых числа. Таких номеров в эталонных вопросах 5 из 24.
    """
    assert tokenize("информационное письмо № ИН-03-23/109") == [
        "информацион",
        "письм",
        "ин-03-23/109",
    ]


def test_number_with_a_slash_stays_one_token():
    # в поле `number` у актов корпуса такая форма встречается дважды
    assert split_tokens("Положение 1/801-П") == ["положение", "1/801-п"]


def test_hyphenated_word_splits_into_two_whole_words():
    """То же `{1,3}` без границы слова резало слово с дефисом.

    «кредитно-денежный» давало «кредитно-ден» и «ежный», и таких слов в
    корпусе 30 800 вхождений при 2368 различных.
    """
    assert split_tokens("кредитно-денежный") == ["кредитно", "денежный"]
    assert split_tokens("банков-нерезидентов") == ["банков", "нерезидентов"]
    assert split_tokens("30-дневный") == ["30", "дневный"]


def test_page_range_is_not_glued():
    # «цифры-цифры» это 26 678 вхождений в корпусе: страницы, телефоны,
    # перечисления. Номером акта они не являются
    assert split_tokens("страницы 75-76") == ["страницы", "75", "76"]


def test_stemmer_leaves_numbers_and_latin_alone():
    assert stem("ин-03-23/109") == "ин-03-23/109"
    assert stem("590-п") == "590-п"
    assert stem("basel") == "basel"
    assert tokenize("принципы принципами принцип") == ["принцип"] * 3


def test_yo_folds_to_e_on_both_sides():
    assert split_tokens("отчётность") == split_tokens("отчетность") == ["отчетность"]
    assert split_tokens("Положение 590-П") == ["положение", "590-п"]
